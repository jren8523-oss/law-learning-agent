def load_pages(txt_path):
    t = Path(txt_path).read_text(encoding="utf-8")
    pages = {}
    for m in re.finditer(r"===== PDF第(\d+)页 =====\n(.*?)(?=\n\n===== PDF第|\Z)", t, re.S):
        pages[int(m.group(1))] = m.group(2).rstrip()
    return pages


def main():
    for b in BOOKS:
        pages = load_pages(b["txt"])
        out = Path(b["out"])
        out.mkdir(parents=True, exist_ok=True)
        for fname, title, a, bz in b["chapters"]:
            body = []
            for p in range(a, bz + 1):
                if p in pages and pages[p].strip():
                    body.append(f"<!-- PDF第{p}页 -->\n\n{pages[p].strip()}")
            text = "\n\n".join(body)
            header = f"# {b['book']} · {title}\n\n> 来源：{b['src']}（PDF 第 {a}–{bz} 页）\n\n---\n\n"
            (out / fname).write_text(header + text + "\n", encoding="utf-8")
            print(f"✓ {b['out']}/{fname}  PDF {a}–{bz}  {len(text)} 字", flush=True)
        print(f"✅ {b['book']} 切章完成（{len(b['chapters'])} 文件）", flush=True)


if __name__ == "__main__":
    main()
