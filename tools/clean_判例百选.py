# 1) 按页码排序重建有序正文（仅正文 17–516）
t = SRC.read_text(encoding="utf-8")
pages = {}
for m in re.finditer(r"===== PDF第(\d+)页 =====\n(.*?)(?=\n\n===== PDF第|\Z)", t, re.S):
    pages[int(m.group(1))] = m.group(2)
body = "\n\n".join(pages[p].strip() for p in range(17, 517) if p in pages)

# 2) 清洗
def clean(s: str) -> str:
    # HTML 标签（删标签保留文本）
    s = re.sub(r"<img[^>]*/?>", "", s)
    s = re.sub(r"<br\s*/?>", "", s)
    s = re.sub(r"</?(div|table|tr|td|th|tbody|thead|span|p)[^>]*>", "", s)
    # LaTeX 残留（脚注星号 $^{*}$ 等）
    s = re.sub(r"\$[^$\n]*\$", "", s)
    # 页眉残行
    s = re.sub(r"^\s*(判例百选系列|民法判例百选|判例百选|民法判例百选系列)\s*$", "", s, flags=re.M)
    # 多空行压缩为单空行
    s = re.sub(r"\n{3,}", "\n\n", s)
    return s

body = clean(body)

# 3) 小节标题规范化
body = re.sub(r"^#{2}\s*[☑☐]?\s*(事实概要|判决要旨|评析|参考文献)\s*$", r"### \1", body, flags=re.M)
# 评析下的 Ⅰ/Ⅱ/Ⅲ 降为四级
body = re.sub(r"^#{2}\s+([ⅠⅡⅢⅣⅤ])\s*", r"#### \1 ", body, flags=re.M)
# 后记标题降为 H2
body = re.sub(r"^#\s+法律共同体的三重要约[^\n]*$", "## 法律共同体的三重要约（代后记）", body, flags=re.M)
# 删除其余残留 H1（旧案例标题，将由注入的新标题取代）
body = re.sub(r"^#\s+[^\n]*$", "", body, flags=re.M)

# 4) 注入案例标题（倒序，避免位置偏移）
anchors = [m.start() for m in re.finditer(r"^### 事实概要\s*$", body, flags=re.M)]
if len(anchors) != 100:
    raise SystemExit(f"事实概要锚点 {len(anchors)} != 100，中止")
for i in range(99, -1, -1):
    pos = anchors[i]
    head = body[:pos].rstrip("\n")
    author_start = head.rfind("\n") + 1  # 作者行起始
    # 往前找案件名称行（作者行前一个非空行）
    prev = body[:author_start].rstrip("\n")
    prev_start = prev.rfind("\n") + 1
    prev_line = prev[prev_start:].strip()
    looks_like_case = any(k in prev_line for k in ("|", "诉", "纠纷案", "判决书", "裁定书", "指导性案例"))
    insert_at = prev_start if looks_like_case else author_start
    block = f"## {i+1:03d} {TITLES[i]}\n\n"
    body = body[:insert_at] + block + body[insert_at:]

# 5) 分编输出
def dump(name, a, b):
    seg = "\n\n".join(pages[p].strip() for p in range(a, b + 1) if p in pages)
    seg = clean(seg)
    seg = re.sub(r"^#{2}\s*[☑☐]?\s*(事实概要|判决要旨|评析|参考文献)\s*$", r"### \1", seg, flags=re.M)
    seg = re.sub(r"^#{2}\s+([ⅠⅡⅢⅣⅤ])\s*", r"#### \1 ", seg, flags=re.M)
    # 从已注入标题的 body 中截取本编范围（按标题切分更稳）
    title_head = f"## {a:03d} "
    title_tail = f"## {b+1:03d} " if b < 100 else None
    start = body.index(title_head)
    end = body.index(title_tail) if title_tail else len(body)
    chunk = body[start:end].strip()
    header = f"# 民法判例百选 · {name.split('-',1)[1].removesuffix('.md')}\n\n> 来源：民法判例百选.pdf（PDF 第 {a}–{b} 页，共 {b-a+1} 页）\n\n---\n\n"
    (OUT_DIR / name).write_text(header + chunk + "\n", encoding="utf-8")
    n = len(re.findall(r"^## \d{3} ", chunk, flags=re.M))
    print(f"✓ {name}: 案例 {n} 篇，{len(chunk)} 字")

